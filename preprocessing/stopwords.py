class StopwordFilter:
    """Filters out common stopwords from token sequences or text."""

    def __init__(self, custom_stopwords: Set[str] = None):
        self.stopwords = set(DEFAULT_ENGLISH_STOPWORDS)
        if custom_stopwords:
            self.stopwords.update(custom_stopwords)

    def filter_tokens(self, tokens: List[str]) -> List[str]:
        """Filters a list of word tokens, removing stopwords."""
        return [t for t in tokens if t.lower() not in self.stopwords]

    def remove_stopwords_from_text(self, text: str) -> str:
        """Removes stopwords from a string of text."""
        words = text.split()
        filtered = [w for w in words if w.lower().strip(".,!?:;\"'()[]{}") not in self.stopwords]
        return " ".join(filtered)
